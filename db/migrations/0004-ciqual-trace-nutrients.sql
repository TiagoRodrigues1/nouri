-- A nutrient for an amount in grams, rounded to the thousandth the journal stores, as catalogFood does.
CREATE FUNCTION pg_temp.scaled(per100 numeric, grams numeric) RETURNS numeric LANGUAGE sql IMMUTABLE AS $$
  SELECT trim_scale(round(per100 * grams / 100, 3))
$$;

UPDATE food_entries e SET
  kcal_milli = COALESCE(e.kcal_milli, round(f.kcal * (e.quantity->>'amount')::numeric * 10)),
  protein_milli = COALESCE(e.protein_milli, round(f.protein_g * (e.quantity->>'amount')::numeric * 10)),
  carbs_milli = COALESCE(e.carbs_milli, round(f.carbs_g * (e.quantity->>'amount')::numeric * 10)),
  fat_milli = COALESCE(e.fat_milli, round(f.fat_g * (e.quantity->>'amount')::numeric * 10)),
  revision = e.revision + 1,
  updated_at = now()
FROM ciqual_filled f
WHERE e.deleted_at IS NULL
  AND e.catalog_ref->>'provider' = 'ciqual'
  AND e.catalog_ref->>'version' = '2025'
  AND e.catalog_ref->>'id' = f.id
  AND e.quantity->>'unit' = 'g'
  AND ((e.kcal_milli IS NULL AND f.kcal IS NOT NULL)
    OR (e.protein_milli IS NULL AND f.protein_g IS NOT NULL)
    OR (e.carbs_milli IS NULL AND f.carbs_g IS NOT NULL)
    OR (e.fat_milli IS NULL AND f.fat_g IS NOT NULL));

-- A saved meal keeps each food as recorded, and its basis, as JSON. Fill both the same way.
CREATE FUNCTION pg_temp.filled_food(food jsonb) RETURNS jsonb LANGUAGE sql STABLE AS $$
  SELECT CASE
    WHEN f.id IS NULL OR food->'quantity'->>'unit' IS DISTINCT FROM 'g' THEN food
    ELSE jsonb_set(food, '{nutrients}', (food->'nutrients') || jsonb_strip_nulls(jsonb_build_object(
      'kcal', CASE WHEN jsonb_typeof(food->'nutrients'->'kcal') IS DISTINCT FROM 'number' THEN pg_temp.scaled(f.kcal, (food->'quantity'->>'amount')::numeric) END,
      'proteinG', CASE WHEN jsonb_typeof(food->'nutrients'->'proteinG') IS DISTINCT FROM 'number' THEN pg_temp.scaled(f.protein_g, (food->'quantity'->>'amount')::numeric) END,
      'carbsG', CASE WHEN jsonb_typeof(food->'nutrients'->'carbsG') IS DISTINCT FROM 'number' THEN pg_temp.scaled(f.carbs_g, (food->'quantity'->>'amount')::numeric) END,
      'fatG', CASE WHEN jsonb_typeof(food->'nutrients'->'fatG') IS DISTINCT FROM 'number' THEN pg_temp.scaled(f.fat_g, (food->'quantity'->>'amount')::numeric) END
    )))
  END
  FROM (SELECT 1) AS one
  LEFT JOIN ciqual_filled f
    ON food->'catalogRef'->>'provider' = 'ciqual'
    AND food->'catalogRef'->>'version' = '2025'
    AND f.id = food->'catalogRef'->>'id'
$$;

CREATE FUNCTION pg_temp.filled_item(item jsonb) RETURNS jsonb LANGUAGE sql STABLE AS $$
  SELECT CASE WHEN item ? 'basis' THEN jsonb_set(filled, '{basis}', pg_temp.filled_food(item->'basis')) ELSE filled END
  FROM (SELECT jsonb_set(item, '{food}', pg_temp.filled_food(item->'food')) AS filled) AS food_filled
$$;

UPDATE saved_meals m SET
  items = filled.items,
  revision = m.revision + 1,
  updated_at = now()
FROM (
  SELECT id, (SELECT jsonb_agg(pg_temp.filled_item(item) ORDER BY position) FROM jsonb_array_elements(items) WITH ORDINALITY AS listed (item, position)) AS items
  FROM saved_meals
  WHERE deleted_at IS NULL
) AS filled
WHERE filled.id = m.id AND filled.items IS DISTINCT FROM m.items;
